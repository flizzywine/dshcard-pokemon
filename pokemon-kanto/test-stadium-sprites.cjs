const assert = require('node:assert/strict');
let serial = 0;
const revoked = [];
global.URL = { createObjectURL: () => `blob:${++serial}`, revokeObjectURL: url => revoked.push(url) };
require('./public/stadium-sprites.js');
const sprites = global.KantoStadiumSprites;
assert.equal(sprites.importFiles([{name:'1-front-n.gif'}, {name:'1-back-n.gif'}, {name:'1-front-s.gif'}, {name:'bad.gif'}]), 3);
assert.equal(sprites.resolve(1, false, false), 'blob:1');
assert.equal(sprites.resolve(1, true, false), 'blob:2');
assert.equal(sprites.resolve(1, false, true), 'blob:3');
assert.equal(sprites.resolve(1, true, true), null);
assert.equal(sprites.importFiles([{name:'bad.gif'}]), 0);
assert.equal(sprites.resolve(1, false, false), 'blob:1');
assert.equal(sprites.importFiles([{name:'25-FRONT-N.GIF'}, {name:'25-front-n.gif'}]), 1);
assert.deepEqual(revoked, ['blob:1', 'blob:2', 'blob:3']);
assert.equal(sprites.resolve(25, false, false), 'blob:4');
sprites.clear();
assert.equal(sprites.count, 0);
assert.equal(revoked.at(-1), 'blob:4');
